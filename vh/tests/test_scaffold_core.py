"""Scaffold core: walker routing, exclusions, dedupe and output format."""

from __future__ import annotations

import os
from pathlib import Path

from vh.scaffold import common


class FakePack:
    name = "fake"
    extensions: tuple[str, ...] = (".fake",)

    def __init__(self) -> None:
        self.scanned: list[str] = []

    def excluded(self, relpath: str) -> bool:
        return relpath.endswith("skip.fake")

    def scan(self, relpath: str, text: str) -> tuple[list[common.Row], int]:
        self.scanned.append(relpath)
        return [common.Row("query param", relpath, 1, "q", "<module>", "http")], 0


def test_walker_routes_by_extension_and_excludes(tmp_path: Path) -> None:
    for name in (
        ".hidden",
        "node_modules",
        "vendor",
        "fixtures",
        "__fixtures__",
        "mocks",
        "__mocks__",
        "examples",
        "samples",
        "docs",
        "static",
        "repo_VULNHUNT_RESULTS_2026-01-01",
    ):
        (tmp_path / name).mkdir()
        (tmp_path / name / "x.fake").write_text("req.query.q")
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "keep.fake").write_text("q")
    (tmp_path / "src" / "skip.fake").write_text("q")
    (tmp_path / "src" / "other.js").write_text("q")

    pack = FakePack()
    result = common.scan_repo(tmp_path, [pack])

    assert [row.file for row in result.rows] == ["src/keep.fake"]
    assert pack.scanned == ["src/keep.fake"]
    assert result.skipped == 0
    assert result.packs == ["fake"]


def test_bad_files_do_not_abort(tmp_path: Path) -> None:
    (tmp_path / "bad.fake").write_bytes(b"\xff\xfe req.query.q")
    (tmp_path / "big.fake").write_bytes(b"x" * (common.MAX_FILE_BYTES + 1))
    locked = tmp_path / "locked.fake"
    locked.write_text("q")
    os.chmod(locked, 0o000)

    pack = FakePack()
    result = common.scan_repo(tmp_path, [pack])

    assert [row.file for row in result.rows] == ["bad.fake"]
    assert pack.scanned == ["bad.fake"]
    assert result.skipped == 2


def test_dedup_key_and_sort(tmp_path: Path) -> None:
    (tmp_path / "b.fake").write_text("")

    class DupPack(FakePack):
        def scan(self, relpath: str, text: str) -> tuple[list[common.Row], int]:
            return (
                [
                    common.Row("body field", "b.fake", 5, "z", "handler", "http"),
                    common.Row("query param", "b.fake", 2, "a", "handler", "http"),
                    common.Row("query param", "b.fake", 5, "z", "handler", "http"),
                    common.Row("query param", "b.fake", 5, "z", "other", "http"),
                ],
                0,
            )

    result = common.scan_repo(tmp_path, [DupPack()])
    assert [(r.line, r.source_type, r.variable, r.entry_point) for r in result.rows] == [
        (2, "query param", "a", "handler"),
        (5, "body field", "z", "handler"),
        (5, "query param", "z", "handler"),
        (5, "query param", "z", "other"),
    ]


def test_output_format(tmp_path: Path) -> None:
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.fake").write_text("q")
    rendered = common.render(common.scan_repo(tmp_path, [FakePack()]))
    lines = rendered.splitlines()
    assert lines[:8] == [
        "# Inputs scaffold",
        "",
        "Generated by `vh scaffold-inputs`. This is a floor, not a ceiling: "
        "recon adds what it misses.",
        "",
        "Packs: fake",
        "Rows: 1",
        "Skipped files: 0",
        "Unresolved sites: 0",
    ]
    assert lines[9] == "| # | Source Type | Location | Variable | Entry Point | Trust Hint |"
    assert lines[11] == "| 1 | query param | src/a.fake:1 | `q` | <module> | http |"

    empty = common.render(common.scan_repo(tmp_path / "src", []))
    assert "Packs: none" in empty
    assert "Rows: 0" in empty
