"""Shared scaffold primitives: the row shape, the pack interface and the walker.

The scaffold is a mechanical floor for the input inventory. It is deliberately
line/regex based (no parser, no runtime dependency); misses are expected.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

SKIP_SEGMENTS = frozenset(
    {
        "node_modules",
        "vendor",
        "fixtures",
        "__fixtures__",
        "mocks",
        "__mocks__",
        "examples",
        "samples",
        "docs",
        "static",
    }
)
MAX_FILE_BYTES = 2 * 1024 * 1024


@dataclass(frozen=True, order=True)
class Row:
    source_type: str
    file: str
    line: int
    variable: str
    entry_point: str
    trust_hint: str


class Pack(Protocol):
    name: str
    extensions: tuple[str, ...]

    def excluded(self, relpath: str) -> bool: ...

    def scan(self, relpath: str, text: str) -> tuple[list[Row], int]: ...


@dataclass
class ScanResult:
    rows: list[Row]
    skipped: int
    unresolved: int
    packs: list[str]


def _skippable_dir(name: str) -> bool:
    return name.startswith(".") or "_VULNHUNT_RESULTS_" in name or name in SKIP_SEGMENTS


def _pack_for(name: str, relpath: str, packs: Sequence[Pack]) -> list[Pack]:
    return [p for p in packs if name.endswith(p.extensions) and not p.excluded(relpath)]


def scan_repo(repo: Path, packs: Sequence[Pack]) -> ScanResult:
    """Walk *repo* once and collect rows from every matching pack."""
    rows: list[Row] = []
    skipped = 0
    unresolved = 0
    matched: list[str] = []
    repo = Path(repo)
    for root, dirs, files in os.walk(repo):
        dirs[:] = sorted(d for d in dirs if not _skippable_dir(d))
        root_path = Path(root)
        relroot = root_path.relative_to(repo).parts if root_path != repo else ()
        for name in sorted(files):
            relpath = "/".join(relroot + (name,))
            chosen = _pack_for(name, relpath, packs)
            if not chosen:
                continue
            path = root_path / name
            try:
                if path.stat().st_size > MAX_FILE_BYTES:
                    skipped += 1
                    continue
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                skipped += 1
                continue
            for pack in chosen:
                if pack.name not in matched:
                    matched.append(pack.name)
                pack_rows, pack_unresolved = pack.scan(relpath, text)
                rows.extend(pack_rows)
                unresolved += pack_unresolved
    return ScanResult(_dedupe(rows), skipped, unresolved, matched)


def _dedupe(rows: list[Row]) -> list[Row]:
    seen: set[tuple[str, int, str, str, str]] = set()
    kept: list[Row] = []
    for row in rows:
        key = (row.file, row.line, row.source_type, row.variable, row.entry_point)
        if key in seen:
            continue
        seen.add(key)
        kept.append(row)
    return sorted(kept, key=lambda r: (r.file, r.line, r.source_type))


def render(result: ScanResult) -> str:
    packs = ", ".join(result.packs) if result.packs else "none"
    out = [
        "# Inputs scaffold",
        "",
        "Generated by `vh scaffold-inputs`. This is a floor, not a ceiling: "
        "recon adds what it misses.",
        "",
        f"Packs: {packs}",
        f"Rows: {len(result.rows)}",
        f"Skipped files: {result.skipped}",
        f"Unresolved sites: {result.unresolved}",
        "",
        "| # | Source Type | Location | Variable | Entry Point | Trust Hint |",
        "|---|---|---|---|---|---|",
    ]
    for index, row in enumerate(result.rows, 1):
        location = f"{row.file}:{row.line}"
        out.append(
            f"| {index} | {row.source_type} | {location} | `{row.variable}` "
            f"| {row.entry_point} | {row.trust_hint} |"
        )
    return "\n".join(out) + "\n"
